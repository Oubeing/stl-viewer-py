GLYPH_WIDTH = 5
GLYPH_HEIGHT = 7
GLYPH_SPACING = 1


def glyph(char: str) -> np.ndarray:
    """返回单字符 7x5 布尔矩阵。未知字符回退为空格。"""
    rows = _GLYPHS_HEX.get(char, _GLYPHS_HEX.get(char.upper(), _GLYPHS_HEX[" "]))
    bits = np.array([[(row >> (GLYPH_WIDTH - 1 - c)) & 1 for c in range(GLYPH_WIDTH)]
                     for row in rows], dtype=bool)
    return bits


def text_mask(text: str, scale: int = 1) -> np.ndarray:
    """把字符串渲染为布尔掩膜，(7*scale) x (总宽*scale)。"""
    scale = max(int(scale), 1)
    if not text:
        return np.zeros((GLYPH_HEIGHT * scale, 0), dtype=bool)
    cols = []
    for i, ch in enumerate(text):
        if i:
            cols.append(np.zeros((GLYPH_HEIGHT, GLYPH_SPACING), dtype=bool))
        cols.append(glyph(ch))
    mask = np.concatenate(cols, axis=1)
    if scale > 1:
        mask = np.repeat(np.repeat(mask, scale, axis=0), scale, axis=1)
    return mask


def text_size(text: str, scale: int = 1) -> tuple:
    """返回 (宽, 高) 像素。"""
    scale = max(int(scale), 1)
    if not text:
        return 0, GLYPH_HEIGHT * scale
    w = len(text) * GLYPH_WIDTH + (len(text) - 1) * GLYPH_SPACING
    return w * scale, GLYPH_HEIGHT * scale
