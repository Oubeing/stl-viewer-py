TRANSLATIONS = {"EN": _EN, "CH": _ZH}
for _code, _table in _PARTIAL.items():
    TRANSLATIONS[_code] = {**_EN, **_table}


class Translator:
    """运行时翻译器（对应原程序 Extras > Language 切换）。"""

    def __init__(self, language: str = "EN"):
        self.language = language if language in TRANSLATIONS else "EN"

    def set_language(self, language: str) -> None:
        if language in TRANSLATIONS:
            self.language = language

    @property
    def table(self) -> dict:
        return TRANSLATIONS.get(self.language, _EN)

    def tr(self, key: str, *args) -> str:
        text = self.table.get(key) or _EN.get(key) or key
        if args:
            try:
                return text.format(*args)
            except (IndexError, KeyError):
                return text
        return text

    def __call__(self, key: str, *args) -> str:
        return self.tr(key, *args)

    @staticmethod
    def language_names() -> list:
        return LANGUAGES
